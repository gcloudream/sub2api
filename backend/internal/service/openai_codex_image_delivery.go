package service

import "strings"

const codexImageDeliveryMarker = "<sub2api-codex-image-delivery>"

// Embedded from the reviewed delivery-instructions.txt; no runtime filesystem
// dependency is needed on the gateway host.
const codexImageDeliveryText = `Image delivery is part of completing the user's current image request, only when this turn actually generates a new image. After the native image_generation tool finishes, do not end with only a statement such as "generated". Save the actual generated image and include a local image preview in your final reply, using tools that are already available in this same Codex session. Do not export old images during ordinary text or coding turns.

If an existing local image tool already returned a saved file, reuse that file. For a hosted image_generation_call whose result has no local file, use the existing local execution/file tool to export the already-generated bytes from THIS session's rollout. This is local file handling, not another image API or another generation. Do not ask the user to install tools, configure keys, change provider settings, or run the export themselves. Do not delegate the export to another agent or another thread.

On Unix-like systems, first check for an existing python3 executable and use it for a Python export; do not assume a python alias exists. If python3 is absent, choose another already-available runtime or file tool. A missing command, nonzero exit code, missing output file, parsing or decoding error, or other file-handling failure is an export failure: retry only the export of the same completed image_generation_call ID and result. Never call image_generation again to repair an export or file operation.

Use CODEX_THREAD_ID from the execution tool's environment, never CODEX_SESSION_ID. Locate only a rollout filename containing that exact thread UUID under CODEX_HOME/sessions (or the user's .codex/sessions if CODEX_HOME is unset), and verify its session_meta payload.id equals that UUID before reading its records. Do not read any other chat, auth file, or credential. Within that file, select only completed response_item payloads of type image_generation_call from the CURRENT turn: use the latest task_started event and its turn_id as the boundary, verify any turn_context belongs to that same turn, and ignore all image records from earlier turns. A later turn_context for the same turn is not a new boundary. If the current turn cannot be identified, stop rather than selecting the last image in the conversation. Ignore an incomplete last JSONL line. If persistence is still pending, retry only that same file for at most 20 seconds; do not generate a replacement image if an export is delayed or fails.

Decode result base64 locally without printing the base64 or rollout contents. Preserve the original bytes. Use the user's requested destination; otherwise save inside the current workspace's output/images/ directory. Make a unique filename from a safely sanitized image call ID (ASCII letters, digits, underscore and hyphen only) and SHA-256; resolve the target and verify it remains inside the chosen output directory. Choose PNG/JPEG/WebP from the bytes, avoid overwriting a different existing file, and reuse an existing file only if its hash is identical. Use a platform-appropriate existing runtime or file tool; do not install software or bypass the client's existing filesystem permissions.

Verify the file exists and its hash matches the decoded result. The export tool must construct and return a small JSON object containing path, sha256, image_markdown, and download_markdown. Both Markdown values must use that same complete ABSOLUTE local path, with forward slashes on Windows and a <...> target when needed for spaces or parentheses; do not use file://. For example, image_markdown is ![Generated image](</absolute/workspace/output/images/image.png>) and download_markdown is [Download image](</absolute/workspace/output/images/image.png>). The final reply must copy these verified image_markdown and download_markdown strings exactly; NEVER shorten the preview target to output/... or another relative path, even if the download link is absolute. Do not merely provide code or say it was saved without a successful file operation. If this client truly has no readable current rollout, no existing local execution/file tool, or no permission to save, explain that limitation truthfully and keep the already-generated result; never claim a nonexistent preview or regenerate solely to repair delivery.
`

const codexImageDeliveryInstructions = codexImageDeliveryMarker + "\n" + codexImageDeliveryText + "\n</sub2api-codex-image-delivery>"

// applyCodexImageDeliveryInstructions is called only inside the caller's
// authorized Codex bridge gate. It describes actual client-side file operations;
// it does not manufacture local tools, saved paths or completion events.
func applyCodexImageDeliveryInstructions(reqBody map[string]any) bool {
	if len(reqBody) == 0 ||
		isCodexSparkModel(firstNonEmptyString(reqBody["model"])) ||
		!codexToolsContainType(reqBody["tools"], "image_generation") ||
		codexImageDeliveryDeclaresLocalTool(reqBody) {
		return false
	}
	existing, isString := reqBody["instructions"].(string)
	if raw, exists := reqBody["instructions"]; exists && raw != nil && !isString {
		return false
	}
	if strings.Contains(existing, codexImageDeliveryMarker) {
		return false
	}
	if existing == "" {
		reqBody["instructions"] = codexImageDeliveryInstructions
	} else {
		reqBody["instructions"] = existing + "\n\n" + codexImageDeliveryInstructions
	}
	return true
}

func codexImageDeliveryDeclaresLocalTool(reqBody map[string]any) bool {
	if codexImageDeliveryToolsContainLocalFunction(reqBody["tools"], "") {
		return true
	}
	input, _ := reqBody["input"].([]any)
	for _, raw := range input {
		item, ok := raw.(map[string]any)
		if !ok || strings.TrimSpace(firstNonEmptyString(item["type"])) != "additional_tools" {
			continue
		}
		if codexImageDeliveryToolsContainLocalFunction(item["tools"], "") {
			return true
		}
	}
	return false
}

func codexImageDeliveryToolsContainLocalFunction(rawTools any, namespace string) bool {
	tools, _ := rawTools.([]any)
	for _, raw := range tools {
		tool, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		kind := strings.TrimSpace(firstNonEmptyString(tool["type"]))
		name := strings.TrimSpace(firstNonEmptyString(tool["name"]))
		if kind == "namespace" {
			nextNamespace := name
			if namespace != "" {
				nextNamespace = namespace + "." + name
			}
			if codexImageDeliveryToolsContainLocalFunction(tool["tools"], nextNamespace) {
				return true
			}
			continue
		}
		if kind != "function" && kind != "custom" {
			continue
		}
		if name == "" {
			if function, ok := tool["function"].(map[string]any); ok {
				name = strings.TrimSpace(firstNonEmptyString(function["name"]))
			}
		}
		if name == codexImageGenerationFunctionToolName ||
			(namespace == "image_gen" && name == "imagegen") ||
			(strings.TrimSpace(firstNonEmptyString(tool["namespace"])) == "image_gen" && name == "imagegen") {
			return true
		}
	}
	return false
}
